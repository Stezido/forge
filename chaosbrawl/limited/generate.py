#!/usr/bin/env python3
"""Rebuild provisional limited data from reviewed source records; never edits MSE."""
from collections import Counter
import argparse
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[2]
EDITION=ROOT/'forge-gui/res/editions/Chaos Brawl Local Test.txt'
BLOCK_NAME='Chaos Brawl - The Foul Realms Beta'

def records():
    cards={}; generated=set()
    for path in sorted((ROOT/'chaosbrawl/batches').glob('*/source.json')):
        doc=json.loads(path.read_text())
        cards.update({c['id']:c for c in doc['cards']})
        generated.update(doc.get('generatedOnlyIds',[]))
    return [cards[cid] for cid in sorted(cards) if not cards[cid]['token'] and cid not in generated]

CONFIRMED = {c['id']: c for c in json.loads((Path(__file__).parent/'confirmed-ratings.json').read_text())['ratings']}


def score(card):
    """First-pass limited strength, not a balance claim or printed card property."""
    if card['id'] in CONFIRMED:
        confirmed = CONFIRMED[card['id']]
        if confirmed['name'] != card['name']:
            raise ValueError('Confirmed rating identity/name differs: ' + card['id'])
        return confirmed['score']
    text=card['rulesText'].lower(); mv=card['manaValue']; types=card['typeLine']
    value=43.0
    if 'Land' in types:
        return 64 if len(re.findall(r'\{[WUBRG]\}',card['rulesText']))>1 or ' or ' in text else 52
    if 'Creature' in types:
        def number(x):return float(x) if re.fullmatch(r'\d+',x or '') else 2
        power=number(card['power']); toughness=number(card['toughness'])
        etb=re.search(r'enters[^.\n]*?with (one|two|three|four|five|six|\d+) drunken',text)
        if etb:
            words={'one':1,'two':2,'three':3,'four':4,'five':5,'six':6}
            counters=words.get(etb[1],int(etb[1]) if etb[1].isdigit() else 0)
            power+=counters;toughness+=counters
        value+=10+min(15,max(-12,(power+toughness-2*mv)*3))
        for keyword,bonus in [('flying',9),('lifelink',5),('deathtouch',7),('first strike',4),('double strike',7),('haste',3),('trample',3),('ward',3)]:
            if keyword in text:value+=bonus
        if 'defender' in text:value-=9
        if 'upkeep' in text and ('sacrifice' in text or 'pay ' in text):value-=5
    if re.search(r'(destroy|exile) target (creature|nonland|permanent)',text):value+=25
    if 'target creature gets -' in text:value+=16
    if 'counter target' in text:value+=9
    if 'draw' in text:value+=9 if 'draw a card' in text else 14
    if 'create' in text and ('creature' in text or 'token' in text):value+=7
    if 'whenever' in text:value+=5
    if 'sacrifice a food' in text or 'beer' in text:value+=2
    value-=max(0,mv-4)*3
    if len(card['colors'])>1:value-=3
    if card['rarity']=='Mythic Rare':value+=5
    overrides=json.loads((Path(__file__).parent/'rating-overrides.json').read_text())
    return overrides.get(card['name'],{}).get('score',round(max(10,min(95,value)),1))

def outputs():
    cards=records(); text=EDITION.read_text();code=re.search(r'^Code=(.+)$',text,re.M)[1]
    # Preserve authoritative printing metadata; replace only generated limited sections.
    text=text.split('\n# BEGIN CHAOS BRAWL LIMITED')[0]
    text=re.sub(r'^Booster(?:Slots)?=.*\n','',text,flags=re.M)
    text=text.replace('Type=Custom_Set\n','Type=Custom_Set\nBoosterSlots=Common,CommonOrLand,Uncommon,RareMythic,Wildcard\nBooster=6 Common, 1 CommonOrLand, 3 Uncommon, 1 RareMythic, 1 Wildcard\n')
    ordinary=[c for c in cards if 'Planeswalker' not in c['typeLine'] and c['rarity']!='Basic Land']
    lands=[c for c in cards if 'Land' in c['typeLine'] and c['rarity']=='Basic Land']
    walkers=[c for c in cards if 'Planeswalker' in c['typeLine']]
    sheet=f'fromSheet("{code} limited")'
    text=text.rstrip()+'\n\n# BEGIN CHAOS BRAWL LIMITED — generated by chaosbrawl/limited/generate.py\n'
    for name,base in [('Common','Common'),('CommonOrLand','Common'),('Uncommon','Uncommon'),('RareMythic','Rare'),('Wildcard','Any')]:
        text+=f'\n[{name}]\nBase={base}:{sheet}\n'
        if name=='CommonOrLand':text+=f'Replace=0.5 Any:fromSheet("{code} lands")\n'
        if name=='RareMythic':text+=f'Replace=0.02 Any:fromSheet("{code} planeswalkers")\nReplace=0.1225 Mythic:{sheet}\n'
        if name in ('CommonOrLand','Wildcard'):text+='ExcludeAlreadySelected=true\n'
    for section,entries in [('limited',ordinary),('lands',lands),('planeswalkers',walkers)]:
        text+=f'\n[{section}]\n'+''.join(f'1 {c["name"]}|{code}|[{c["id"][3:]}]\n' for c in entries)
    ranking=sorted({c['name']:c for c in cards}.values(),key=lambda c:(-score(c),c['name']))
    ratings={'schemaVersion':1,'edition':code,'provisional':any(c['id'] not in CONFIRMED for c in cards),'method':'Owner-confirmed 0–100 spreadsheet scores; existing provisional scores retained only for unrated cards.',
             'eligiblePrintings':len(cards),'eligibleNames':len(ranking),'ratings':[{'name':c['name'],'sourceIds':[p['id'] for p in cards if p['name']==c['name']],'score':score(c),'ratingSource':'confirmed' if c['id'] in CONFIRMED else 'provisional','rank':n} for n,c in enumerate(ranking,1)]}
    rarity={'Common':'C','Uncommon':'U','Rare':'R','Mythic Rare':'M','Basic Land':'L','Masterpiece':'S'}
    rnk='// Chaos Brawl limited rankings: confirmed owner scores, provisional fallback for unrated cards.\n//Rank|Name|Rarity|Set\n'+''.join(f'#{n}|{c["name"]}|{rarity[c["rarity"]]}|{code}\n' for n,c in enumerate(ranking,1))
    blocks=ROOT/'forge-gui/res/blockdata/blocks.txt'
    block_text='\n'.join(line for line in blocks.read_text().splitlines() if not line.startswith(BLOCK_NAME+','))+'\n'
    # The custom dual lands are not unlimited basic lands despite their MSE rarity.
    block_text+=f'{BLOCK_NAME}, 3/8/M21, {code}\n'
    result={EDITION:text,blocks:block_text,ROOT/f'forge-gui/res/draft/rankings/{code.lower()}.rnk':rnk,Path(__file__).parent/'ratings.json':json.dumps(ratings,ensure_ascii=False,indent=2)+'\n'}
    hints=json.loads((Path(__file__).parent/'ai-hints.json').read_text())['hints']
    for cid,hint in hints.items():
        path=ROOT/f'forge-gui/res/cardsfolder/custom/chaosbrawl_{cid}.txt'
        script=re.sub(r'^DeckHints:.*\n','',path.read_text(),flags=re.M)
        result[path]=script.rstrip()+'\nDeckHints:'+hint+'\n'
    return result

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit('Generated data differs: '+str(path.relative_to(ROOT)))
        else:path.write_text(text)
    print('Checked' if args.check else 'Generated','291 eligible printings; 50% dual land common slot; 2% planeswalker rare slot; 12-card packs; 3 draft / 8 sealed packs.')
if __name__=='__main__':main()
